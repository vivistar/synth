// Regenerates references.md from references.html (the single source of truth) and writes
// a copy into each Anchorflight skill folder, so the bundled citations never drift.
//
// Run whenever references.html changes:
//   node tools/skills/sync-references.js
//
// No dependencies. Parses the two <tbody> tables in references.html.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const SRC = path.join(ROOT, 'references.html');
const SKILL_DIRS = [
  '.claude/skills/anchorflight-triage',
  '.claude/skills/anchorflight-8gate',
  '.claude/skills/anchorflight-persona',
].map(d => path.join(ROOT, d));

function decode(s) {
  return s
    .replace(/<[^>]+>/g, '')                 // strip tags
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&rsquo;/g, '’')
    .replace(/&mdash;/g, '—')
    .replace(/&ndash;/g, '–')
    .replace(/&rarr;/g, '→')
    .replace(/&#8209;/g, '-')                 // non-breaking hyphen -> hyphen
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function rowsOf(tbodyHtml) {
  return [...tbodyHtml.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map(tr =>
    [...tr[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map(td => decode(td[1]))
  );
}

const html = fs.readFileSync(SRC, 'utf8');
const tbodies = [...html.matchAll(/<tbody[^>]*>([\s\S]*?)<\/tbody>/g)].map(m => m[1]);
if (tbodies.length < 2) { console.error('Expected 2 tables in references.html'); process.exit(1); }

const prosCons = rowsOf(tbodies[0]);   // source, year, type, pros, cons
const guidance = rowsOf(tbodies[1]);   // source, year, type, guidance

let md = `# Anchorflight — research basis

The framework and its synthetic-vs-human verdicts are grounded in the following
peer-reviewed and industry literature on synthetic users in UX / human-centred design.

> **Do not edit this file by hand.** It is generated from \`references.html\` (the single
> source of truth) by \`tools/skills/sync-references.js\`. Update the HTML, then re-run the
> script. The live, linkable version lives at \`references.html\`.

## Key sources — pros and cons

`;
for (const [source, year, type, pros, cons] of prosCons) {
  md += `- **${source}** (${year}, ${type})\n  - Pros: ${pros}\n  - Cons: ${cons}\n`;
}
md += `\n## Best-practice guidance\n\n`;
for (const [source, year, type, guide] of guidance) {
  md += `- **${source}** (${year}, ${type}): ${guide}\n`;
}

for (const dir of SKILL_DIRS) {
  fs.writeFileSync(path.join(dir, 'references.md'), md);
  console.log('wrote', path.relative(ROOT, path.join(dir, 'references.md')));
}
console.log(`done — ${prosCons.length} sources, ${guidance.length} guidance rows`);
